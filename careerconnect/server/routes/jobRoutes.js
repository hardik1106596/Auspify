const router = require("express").Router();
const c = require("../controllers/jobController");
const { protect, allowRoles } = require("../middleware/auth");
router.get("/", c.list);
router.get("/mine", protect, allowRoles("employer", "admin"), c.mine);
router.get("/:id", c.getOne);
router.post("/", protect, allowRoles("employer", "admin"), c.create);
router.patch("/:id", protect, allowRoles("employer", "admin"), c.update);
router.delete("/:id", protect, allowRoles("employer", "admin"), c.remove);
module.exports = router;
